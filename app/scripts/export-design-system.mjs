import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { transformWithOxc } from "vite";

const appRoot = fileURLToPath(new URL("../", import.meta.url));
const checkOnly = process.argv.includes("--check");

// These app-owned data modules have no imports or top-level browser side effects.
// Vite's existing compiler strips TypeScript without adding a dependency.
async function loadDataModule(relativePath) {
  const filename = path.join(appRoot, relativePath);
  const source = await readFile(filename, "utf8");
  const result = await transformWithOxc(source, filename);
  return import(`data:text/javascript;base64,${Buffer.from(result.code).toString("base64")}`);
}

const { neutralColors, colorTokens, spacingTokens, typeTokens, tokenDocument, fontCss } = await loadDataModule("src/design-system/tokens.ts");
const { systemAssets, newComponentBrief } = await loadDataModule("src/design-system/assets.ts");

function declaration(name, value) {
  return `  ${name}: ${value};`;
}

function colorDeclarations(mode) {
  const variables = new Map(colorTokens.map((token) => [token.key, token.variable]));
  return Object.entries(tokenDocument.color[mode]).map(([key, token]) => {
    const value = token.$value;
    if (typeof value === "string") {
      const match = /^\{color\.(neutral|light|dark)\.([^}]+)\}$/.exec(value);
      if (!match || (match[1] !== mode && match[1] !== "neutral") || !tokenDocument.color[match[1]][match[2]]) {
        throw new Error(`Invalid ${mode} color alias: ${value}`);
      }
      const target = match[1] === "neutral"
        ? neutralColors.find((token) => token.key === match[2])?.variable
        : variables.get(match[2]) ?? `--dc-${match[2]}`;
      if (!target) throw new Error(`Missing CSS variable for ${value}`);
      return declaration(variables.get(key) ?? `--dc-${key}`, `var(${target})`);
    }
    if (!/^#[a-f0-9]{6}$/i.test(value.hex)) throw new Error(`Missing hex value for color.${mode}.${key}`);
    return declaration(variables.get(key) ?? `--dc-${key}`, value.hex);
  });
}

function dimension(value) {
  return `${value.value}${value.unit}`;
}

const foundationDeclarations = [
  ...neutralColors.map((token) => declaration(token.variable, token.value)),
  declaration("--dc-font-sans", fontCss),
  declaration("--dc-font-weight", tokenDocument.font.regular.$value),
  ...spacingTokens.map((token) => declaration(token.variable, dimension(tokenDocument.space[token.name].$value))),
  ...typeTokens.flatMap((token) => [
    declaration(token.variable, dimension(tokenDocument.typography[token.key].$value.fontSize)),
    declaration(`--dc-type-${token.key}-line`, `${token.lineHeight}px`),
  ]),
  declaration("--dc-border-width", dimension(tokenDocument.border.width.$value)),
  ...Object.entries(tokenDocument.radius).map(([key, token]) => declaration(`--dc-radius-${key}`, dimension(token.$value))),
];

const css = [
  "/* Generated by scripts/export-design-system.mjs. Edit tokens.ts, then rebuild. */",
  ":root,",
  '.dc-system[data-preview-theme="light"] {',
  ...colorDeclarations("light"),
  ...foundationDeclarations,
  "}",
  "",
  '.dc-system[data-preview-theme="dark"],',
  '.device-screen:has(.daily-culture-app[data-theme="dark"]) {',
  ...colorDeclarations("dark"),
  "}",
  "",
].join("\n");

const outputs = new Map([
  ["src/design-system/tokens.css", css],
  ["public/design-system/daily-culture.tokens.json", `${JSON.stringify(tokenDocument, null, 2)}\n`],
  ["public/design-system/daily-culture-component-brief.md", newComponentBrief],
]);

for (const asset of systemAssets) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(asset.id)) throw new Error(`Invalid asset filename: ${asset.id}`);
  outputs.set(`public/design-system/${asset.id}.svg`, `${asset.svg}\n`);
}

for (const [relativePath, content] of outputs) {
  const filename = path.join(appRoot, relativePath);
  if (checkOnly) {
    const current = await readFile(filename, "utf8").catch(() => null);
    if (current !== content) throw new Error(`${relativePath} is stale. Run npm run export:design-system.`);
  } else {
    await mkdir(path.dirname(filename), { recursive: true });
    await writeFile(filename, content, "utf8");
  }
}

console.log(`Design system: ${checkOnly ? "verified" : "generated"} ${outputs.size} files from authored sources.`);
