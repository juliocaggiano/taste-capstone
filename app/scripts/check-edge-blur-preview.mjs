import { chromium } from 'playwright';
import fs from 'node:fs/promises';
const browser = await chromium.launch();
const page = await browser.newPage({viewport:{width:1500,height:1250}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4173/edge-blur-study.html');
await page.locator('iframe').nth(2).waitFor();
await page.waitForTimeout(1600);
await page.getByRole('button',{name:'Middle',exact:true}).click();
await page.waitForTimeout(1000);
await page.screenshot({path:'../qa/scroll-edge-blur-2026-09-23/comparison-profile.png',fullPage:true});
const frames=page.frames().filter(f=>f.url().includes('edge-blur-study='));
const states=async()=>Promise.all(frames.map(f=>f.evaluate(()=>({variant:document.querySelector('.daily-culture-app')?.dataset.edgeBlurStudy,scroll:[...document.querySelectorAll('.mobile-scroll')].map(s=>({top:s.scrollTop,max:s.scrollHeight-s.clientHeight})),edges:[...document.querySelectorAll('.scroll-edge-blur')].map(e=>({side:e.className,strength:e.style.getPropertyValue('--edge-strength'),visible:getComputedStyle(e).visibility})),storage:Object.fromEntries(Object.entries(localStorage))}))));
const result={middle:await states()};
await page.getByRole('button',{name:'Home',exact:true}).click();
await page.waitForTimeout(400);
await page.getByRole('button',{name:'Middle',exact:true}).click();
await page.waitForTimeout(1000);
await page.screenshot({path:'../qa/scroll-edge-blur-2026-09-23/comparison-home.png',fullPage:true});
result.home=await states();
await page.getByRole('button',{name:'Bottom',exact:true}).click();
await page.waitForTimeout(1000);
result.bottom=await states();
await page.getByRole('button',{name:'Dark',exact:true}).click();
await page.getByRole('button',{name:'Middle',exact:true}).click();
await page.waitForTimeout(1000);
await page.screenshot({path:'../qa/scroll-edge-blur-2026-09-23/comparison-dark.png',fullPage:true});
result.errors=errors;
await fs.writeFile('../qa/scroll-edge-blur-2026-09-23/first-check.json',JSON.stringify(result,null,2));
console.log(JSON.stringify({errors,variants:result.middle.map(s=>({variant:s.variant,scroll:s.scroll,edges:s.edges})),bottom:result.bottom.map(s=>({variant:s.variant,scroll:s.scroll,edges:s.edges}))},null,2));
await browser.close();
